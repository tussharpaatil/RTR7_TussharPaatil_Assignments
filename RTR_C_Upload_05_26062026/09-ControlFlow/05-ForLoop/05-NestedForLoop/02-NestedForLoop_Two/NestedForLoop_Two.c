// Program Name : NestedForLoop_Two.c

int main(void)
{
	// Variable Declarations
	int x, y, z;

	// Code
	printf("\n=====================================================================\n");
	for (x = 1; x <= 10; x++)
	{
		printf(" x = %d\n", x);
		printf("=>-------------------------------------------------------------------\n\n");
		for (y = 1; y <= 5; y++)
		{
			printf("\t y = %d\n", y);
			printf("\t=>-----------------------------------------------------------\n\n");
			for (z = 1; z <= 3; z++)
			{
				printf("\t\t z = %d\n", z);
			}
			printf("\n=====================================================================\n");
		}
		printf("\n=====================================================================\n");
	}
	return (0);
}
