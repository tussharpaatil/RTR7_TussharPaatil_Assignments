// Program Name : SingleIteratingVariable.c

#include <stdio.h>

int main(void)
{
	// Variable Declarations
	int counter;

	// Code
	printf("\n===================================================================\n");

	printf("Printing Digits 1 to 10 : \n\n");

	for (counter = 0; counter <= 10; counter++)
	{
		printf("\t%d\n", counter);
	}
	printf("\n===================================================================\n");

	return (0);
}
