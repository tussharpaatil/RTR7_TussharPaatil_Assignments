// Program Name : SingleIteratingVariable.c

#include <stdio.h>

int main(void)
{
	// Variable Declarations
	int counter;

	// Code
	printf("\n=======================================================================\n");

	printf("Printing Digits 10 to 1 : \n\n");

	for (counter = 10; counter >= 1; counter--)
	{
		printf("\t %d \n", counter);
	}
	printf("\n=======================================================================\n");

	return (0);
}
